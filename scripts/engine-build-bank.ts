/**
 * Build the puzzle bank (bun): generates puzzles, classifies them with the logical solver and writes
 * src/engine/bank/bank.ts. Long-running for expert puzzles; progress is saved periodically.
 *
 *   bun scripts/engine-build-bank.ts [--per=300] [--expert=300] [--seed=20261011] [--max-attempts=60000]
 *
 * Strategy per attempt: carve a random solved grid (alternating 180°-symmetric and non-symmetric minimal
 * carving), rate it, then file it under its natural difficulty or tune it down (adding clues) to an easier
 * difficulty whose bucket still needs puzzles. Easy puzzles are topped up to 36-42 givens, medium to 28-32.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { countSolutions } from '../src/engine/bruteSolver';
import { ratePuzzle } from '../src/engine/difficulty';
import { tunePuzzle } from '../src/engine/fresh';
import { carvePuzzle, generateSolvedGrid } from '../src/engine/generator';
import { serializeGrid } from '../src/engine/grid';
import { createRng } from '../src/engine/rng';
import type { TechniqueId } from '../src/engine/steps';
import { DIFFICULTIES, type Difficulty } from '../src/engine/types';

const arg = (name: string, def: number) => Number(process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1] ?? def);
const PER = arg('per', 300);
const EXPERT = arg('expert', PER);
const SEED = arg('seed', 20261011);
const MAX_ATTEMPTS = arg('max-attempts', 60000);
const OUT = fileURLToPath(new URL('../src/engine/bank/bank.ts', import.meta.url));

type Entry = [string, number, TechniqueId];
const buckets: Record<Difficulty, Entry[]> = { easy: [], medium: [], hard: [], expert: [] };
const seen = new Set<string>();
const target = (d: Difficulty) => (d === 'expert' ? EXPERT : PER);
const full = (d: Difficulty) => buckets[d].length >= target(d);
const timeSpent: Record<Difficulty, number> = { easy: 0, medium: 0, hard: 0, expert: 0 };
const natural: Record<string, number> = {};

function write() {
  const lines: string[] = [];
  lines.push('/* eslint-disable */');
  lines.push('// GENERATED by scripts/engine-build-bank.ts — do not edit by hand.');
  lines.push(`// ${new Date().toISOString()} seed=${SEED}`);
  lines.push("// Each entry: [puzzle (81 chars, '.' = empty), score, hardest technique id].");
  lines.push("import type { BankData } from './types';");
  lines.push('');
  lines.push('export const BANK: BankData = {');
  for (const d of DIFFICULTIES) {
    const sorted = [...buckets[d]].sort((a, b) => a[1] - b[1]);
    lines.push(`  ${d}: [`);
    for (const e of sorted) lines.push(`    ['${e[0]}', ${e[1]}, '${e[2]}'],`);
    lines.push('  ],');
  }
  lines.push('};');
  lines.push('');
  writeFileSync(OUT, lines.join('\n'));
}

const t0 = performance.now();
let attempts = 0;
let lastSave = performance.now();
while (!DIFFICULTIES.every(full) && attempts < MAX_ATTEMPTS) {
  attempts++;
  const ta = performance.now();
  const rng = createRng((SEED + Math.imul(attempts, 0x9e3779b1)) >>> 0);
  const solution = generateSolvedGrid(rng);
  // Once easy/medium/hard are full, only minimal carving is used (it finds expert puzzles more often).
  const symmetric = !full('hard') && attempts % 2 === 0;
  const carved = carvePuzzle(solution, rng, { symmetric });
  const rating = ratePuzzle(carved, true);
  const nat = rating.difficulty ?? 'unrated';
  natural[nat] = (natural[nat] ?? 0) + 1;
  // Candidate buckets: natural difficulty first, then easier ones that still need puzzles.
  const order: Difficulty[] = [];
  const natIdx = rating.difficulty ? DIFFICULTIES.indexOf(rating.difficulty) : 2; // unrated → tune to hard or easier
  for (let i = natIdx; i >= 0; i--) if (!full(DIFFICULTIES[i])) order.push(DIFFICULTIES[i]);
  for (const d of order) {
    const tuned = tunePuzzle(carved, solution, d, rng);
    if (!tuned) continue;
    const key = serializeGrid(tuned);
    if (seen.has(key)) break;
    if (countSolutions(tuned, 2).count !== 1) throw new Error('non-unique puzzle produced');
    const r = ratePuzzle(tuned, true);
    if (r.difficulty !== d || !r.solved) continue;
    seen.add(key);
    buckets[d].push([key, r.score, r.hardestTechnique ?? 'hidden-single']);
    timeSpent[d] += performance.now() - ta;
    break;
  }
  if (attempts % 100 === 0 || performance.now() - lastSave > 60000) {
    const counts = DIFFICULTIES.map((d) => `${d}=${buckets[d].length}`).join(' ');
    console.log(`attempt ${attempts}: ${counts} natural=${JSON.stringify(natural)} ${((performance.now() - t0) / 1000).toFixed(0)}s`);
    write();
    lastSave = performance.now();
  }
}
write();
console.log('\n=== Bank build summary ===');
console.log(`attempts: ${attempts}, total time ${((performance.now() - t0) / 1000).toFixed(0)}s`);
console.log('natural difficulty of carved puzzles:', JSON.stringify(natural));
for (const d of DIFFICULTIES) {
  const b = buckets[d];
  const clues = b.reduce((n, e) => n + e[0].replace(/\./g, '').length, 0) / Math.max(1, b.length);
  const tech: Record<string, number> = {};
  for (const e of b) tech[e[2]] = (tech[e[2]] ?? 0) + 1;
  console.log(`${d}: ${b.length} puzzles, avg clues ${clues.toFixed(1)}, hardest: ${JSON.stringify(tech)}`);
}
