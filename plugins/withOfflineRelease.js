/**
 * Expo config plugin: strip android.permission.INTERNET from RELEASE builds only.
 *
 * Pencilmark is fully offline. Debug / dev-client builds still need INTERNET to reach Metro, so the
 * permission cannot go in `android.blockedPermissions` (that removes it from every variant).
 * Instead this writes a release source-set manifest, android/app/src/release/AndroidManifest.xml,
 * that marks the permission `tools:node="remove"`. Build-type manifests have higher merge priority
 * than the main manifest and library manifests, so the merged release manifest has no INTERNET.
 *
 * Verify after a release build:
 *   %ANDROID_HOME%\build-tools\36.0.0\aapt2 dump permissions app\build\outputs\apk\release\app-release.apk
 */
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withOfflineRelease.js. Do not edit; re-run expo prebuild. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
  <uses-permission android:name="android.permission.INTERNET" tools:node="remove"/>
</manifest>
`;

const withOfflineRelease = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'release');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), MANIFEST);
      return cfg;
    },
  ]);

module.exports = withOfflineRelease;
